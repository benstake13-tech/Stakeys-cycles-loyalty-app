/**
 * Buy links for a cross-reference entry, cheapest/most-reliable first. The Wheels Mfg
 * DROPOUT number and the OEM codes are the search keys, because UK stockists list by
 * code rather than by bike model.
 */
export function buildCrossRefBuyLinks(h: HangerCrossRef): HangerBuyLink[] {
  const oem = h.oemPartNumbers[0] || h.wheelsMfg;
  const q = encodeURIComponent(`${h.wheelsMfg} derailleur hanger`);
  const oemQ = encodeURIComponent(`${h.brand} ${oem} derailleur hanger`);
  return [
    { retailer: 'eBay UK', url: `https://www.ebay.co.uk/sch/i.html?_nkw=${q}`, note: 'Cheapest — match the shape to the old hanger.' },
    { retailer: 'RearMechHanger.com', url: `https://rearmechhanger.com/?s=${encodeURIComponent(oem)}&post_type=product`, note: 'Hanger specialist with fitment tables.' },
    { retailer: 'BETD', url: `https://betd.co.uk/search?q=${q}`, note: 'UK hanger maker, fast delivery.' },
    { retailer: 'SJS', url: `https://www.sjscycles.co.uk/search/?search=${oemQ}`, note: 'UK workshop supplier, wide hanger stock.' },
    { retailer: 'Wheels Manufacturing', url: `https://wheelsmfg.com/catalogsearch/result/?q=${encodeURIComponent(h.wheelsMfg)}`, note: 'Original DROPOUT source.' },
  ];
}
