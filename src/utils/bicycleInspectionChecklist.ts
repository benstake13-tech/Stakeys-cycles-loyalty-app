export interface SpecificationDetail { name: string; value: string; verification: 'photo-supported' | 'needs-verification' | 'not-assessed' }
export function normaliseSpecificationDetails(componentId: string, raw: unknown, photoSupported = false): SpecificationDetail[] {
  const supplied = Array.isArray(raw) ? raw : [];
  const measurementOnly = ['geometry', 'weight', 'payload', 'available-sizes'].includes(componentId);
  return (COMPONENT_SPEC_FIELDS[componentId] || []).map(name => {
    const found = supplied.find(row => row && typeof row === 'object' && typeof row.name === 'string' && row.name.toLowerCase() === name.toLowerCase());
    const value = typeof found?.value === 'string' ? found.value.trim().slice(0, 250) : '';
    return { name, value, verification: !value ? 'not-assessed' : photoSupported && !measurementOnly ? 'photo-supported' : 'needs-verification' };
  });
}
